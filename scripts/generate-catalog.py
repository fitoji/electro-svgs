#!/usr/bin/env python3
"""Build catalog.json from REA-ing-inversa's generated component documentation.

Usage:
    python3 scripts/generate-catalog.py <path-to>/REA-ing-inversa/docs/componentes.md

The source document is generated by the simulator from its own catalog.ts and
families.ts, so every value here comes from real app data instead of guesses.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "catalog.json"

# Labels from REA-ing-inversa/app/src/ui/Palette.tsx (GROUP_LABEL).
CATEGORY_SLUG = {
    "Alimentación": "alimentacion",
    "Motores": "motor",
    "Potencia": "potencia",
    "Protección": "proteccion",
    "Mando": "mando",
    "Señalización y pulsadores": "senalizacion",
    "Sensores": "sensor",
    "Líneas y cables": "linea",
    "Cargas": "carga",
    "Borneras": "borne",
    "Otros": "otro",
}

ROW = re.compile(
    r"^\|\s*!\[[^\]]*\]\(img/componentes/(\d+)\.svg\)\s*\|"
    r"\s*`(\d+)`\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|"
)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Uso: python3 scripts/generate-catalog.py <docs/componentes.md>")

    source = Path(sys.argv[1]).resolve()
    current_label = None
    entries = []

    for line in source.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^##\s+(.+?)\s*\(\d+\)\s*$", line)
        if heading:
            current_label = heading.group(1)
            continue

        match = ROW.match(line)
        if not match or current_label not in CATEGORY_SLUG:
            continue

        svg_code, code, name, designator, pins = match.groups()
        entries.append(
            {
                "code": int(code),
                "name": name.strip(),
                "designator": "" if designator.strip() == "—" else designator.strip().strip("`"),
                "category": CATEGORY_SLUG[current_label],
                "category_label": current_label,
                "pins": [pin.strip() for pin in pins.split("·") if pin.strip()],
                "file": f"symbols/componentes/{svg_code}.svg",
            }
        )

    # El documento repite algunos códigos dentro de una misma familia; el
    # catálogo debe tener una sola entrada por símbolo.
    unique = {}
    for entry in entries:
        unique.setdefault(entry["code"], entry)
    entries = list(unique.values())
    entries.sort(key=lambda entry: entry["code"])

    missing = [entry["file"] for entry in entries if not (ROOT / entry["file"]).exists()]
    if missing:
        raise SystemExit(f"Faltan SVG referenciados: {missing[:5]}")

    OUTPUT.write_text(
        json.dumps({"source": source.name, "entries": entries}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Generado {OUTPUT.name} con {len(entries)} símbolos desde {source}")


if __name__ == "__main__":
    main()
